#!/usr/bin/env python3
"""Render isolated Dynamo 1.5.1 manifests from the checked-in model settings."""
from copy import deepcopy
from pathlib import Path
import json
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
IMAGES = {
    'frontend': 'nvcr.io/nvidia/ai-dynamo/dynamo-frontend:1.5.1@sha256:2ce6f7484185ccae02381fa90b97330bddf021177960d7c0c0ad4ee83a9874fa',
    'worker': 'nvcr.io/nvidia/ai-dynamo/vllm-runtime:1.5.1@sha256:2b224a823d52a198ec0eeb0e3e4f5cf26cd8a7fc2e9812ee16204b6b1e974870',
    'operator': 'nvcr.io/nvidia/ai-dynamo/kubernetes-operator:1.5.1@sha256:4b8229b913d66fff2111c228e02f65d342b3e136bb1ee2f83892e8a140b96d1d',
}
NIGHTLY = 'nvcr.io/nvidia/ai-dynamo/dynamo-frontend-nightly@sha256:38286598fd3a514a36bfddb90c2f8751350ccb787fabd307361673a534e46c4f'
MODELS = {'qwen': 'qwen3.6-35b-a3b-nvfp4', 'muse': 'muse-glimmer-30b'}
# Qwen migrated back to its original EPP-free graph during approved maintenance.
EPP_ROUTING_ENABLED = {'qwen': False, 'muse': True}


def write(name, documents):
    (HERE / name).write_text('# Generated by generate.py. Review before applying.\n' + yaml.safe_dump_all(documents, sort_keys=False))


def main():
    candidates = []
    kv_sizes = json.loads((HERE / 'effective-kv-block-sizes.json').read_text())
    for short, directory in MODELS.items():
        base = ROOT / 'deploy/models' / directory / 'dynamo'
        graph = yaml.safe_load((HERE / 'inputs' / f'{short}-graph.yaml').read_text())
        old_graph_name = graph['metadata']['name']
        graph['metadata']['name'] += '-151-epp'
        graph['metadata'].setdefault('annotations', {})['token-labs/maintenance-approved'] = '2026-10-07: explicit user approval in upgrade chat'
        frontend, worker = graph['spec']['components']
        served = worker['podTemplate']['spec']['containers'][0]['args']
        model = served[served.index('--served-model-name') + 1]
        front_container = frontend['podTemplate']['spec']['containers'][0]
        frontend['runtimeVersionOverride'] = '1.6.0'
        front_container['image'] = NIGHTLY
        front_container['imagePullPolicy'] = 'IfNotPresent'
        args = front_container['args']
        if '--namespace' in args:
            index = args.index('--namespace')
            del args[index:index + 2]
        worker['type'] = 'decode'
        worker['frontendSidecar'] = 'sidecar-frontend'
        pod = worker['podTemplate']['spec']
        main_container = pod['containers'][0]
        main_container['image'] = IMAGES['worker']
        main_container['imagePullPolicy'] = 'IfNotPresent'
        main_container['args'] += ['--block-size', '128', '--kv-events-config', '{"enable_kv_cache_events":true}']
        pod['containers'].append({
            'name': 'sidecar-frontend', 'image': NIGHTLY,
            'command': ['python3'], 'args': ['-m', 'dynamo.frontend', '--router-mode', 'direct', '--trust-remote-code', '--enable-anthropic-api'],
            'env': [{'name': 'HF_HOME', 'value': '/model-cache'}, {'name': 'HF_MODULES_CACHE', 'value': '/tmp/hf_modules'}, {'name': 'DYN_HTTP_BODY_LIMIT_MB', 'value': '200'}],
            'resources': {'requests': {'cpu': '1', 'memory': '2Gi'}, 'limits': {'cpu': '2', 'memory': '4Gi'}},
        })
        epp = {
            'name': 'Epp', 'type': 'epp', 'replicas': 1,
            'podTemplate': {'spec': {
                'nodeSelector': {'kubernetes.io/hostname': 'controller'},
                'tolerations': [{'key': 'node-role.kubernetes.io/control-plane', 'operator': 'Exists', 'effect': 'NoSchedule'}],
                'containers': [{'name': 'main', 'image': IMAGES['frontend'], 'imagePullPolicy': 'IfNotPresent',
                    'env': [{'name': 'DYN_MODEL_NAME', 'value': model}, {'name': 'DYN_KV_CACHE_BLOCK_SIZE', 'value': str(kv_sizes[short])}],
                    'resources': {'requests': {'cpu': '500m', 'memory': '1Gi'}, 'limits': {'cpu': '2', 'memory': '4Gi'}}}],
            }},
        }
        graph['spec']['components'] = [epp, worker]
        if short == 'qwen':
            graph = yaml.safe_load((HERE / 'inputs/qwen-epp-free-graph.yaml').read_text())
        write(f'{short}-graph.yaml', [graph])
        write(f'{short}-diagnostic.yaml', [{'apiVersion': 'v1', 'kind': 'Service',
            'metadata': {'name': f'dynamo-151-{short}-diagnostic', 'namespace': 'token-labs'},
            'spec': {'selector': {'nvidia.com/dynamo-namespace': 'token-labs-' + graph['metadata']['name'], 'nvidia.com/dynamo-component': worker['name']} if short != 'qwen' else {'token-labs/model-id': 'qwen36-nvfp4-frontend', 'token-labs/slot': 'blue'},
                     'ports': [{'name': 'http', 'port': 8000, 'targetPort': 8000}]}}])
        route = {
            'apiVersion': 'gateway.networking.k8s.io/v1', 'kind': 'HTTPRoute',
            'metadata': {'name': f'dynamo-151-{short}-canary', 'namespace': 'token-labs'},
            'spec': {'parentRefs': [{'name': 'token-labs-gateway'}],
                'rules': [{'matches': [{'path': {'type': 'PathPrefix', 'value': f'/upgrade/dynamo-151/{short}'}}],
                    'filters': [{'type': 'URLRewrite', 'urlRewrite': {'path': {'type': 'ReplacePrefixMatch', 'replacePrefixMatch': '/'}}},
                                {'type': 'RequestHeaderModifier', 'requestHeaderModifier': {'set': [{'name': 'X-Gateway-Model-Name', 'value': model}]}}],
                    'backendRefs': [{'group': 'inference.networking.k8s.io', 'kind': 'InferencePool', 'name': graph['metadata']['name'] + '-pool', 'port': 8000}],
                    'timeouts': {'request': '3600s'}}]},
        }
        if not EPP_ROUTING_ENABLED[short]:
            stable_name = yaml.safe_load(
                (HERE / 'inputs' / f'{short}-stable-service.yaml').read_text())['metadata']['name']
            route['spec']['rules'][0]['backendRefs'] = [
                {'name': stable_name, 'port': 8000}]
        write(f'{short}-canary-route.yaml', [route])
        candidate = yaml.safe_load((HERE / 'inputs' / f'{short}-frontend.yaml').read_text())
        candidate['metadata']['name'] = candidate['metadata']['name'].removesuffix('-151-check').removesuffix('-green') + '-151-check'
        labels = {'token-labs/model-id': candidate['metadata']['name'], 'token-labs/slot': 'candidate-151'}
        candidate['spec']['selector']['matchLabels'] = labels
        candidate['spec']['template']['metadata']['labels'] = deepcopy(labels)
        candidate['spec']['template']['spec']['containers'][0]['image'] = IMAGES['frontend']
        service = {'apiVersion': 'v1', 'kind': 'Service', 'metadata': {'name': candidate['metadata']['name'], 'namespace': 'token-labs'},
                   'spec': {'selector': labels, 'ports': [{'name': 'http', 'port': 8000, 'targetPort': 'http'}]}}
        candidates += [candidate, service]
        api = deepcopy(candidate)
        api['metadata']['name'] = candidate['metadata']['name'].replace('-151-check', '-151-api')
        if short == 'qwen':
            api['spec']['replicas'] = 0  # Retired; stable traffic uses the old blue frontend.
        labels = {'token-labs/model-id': candidate['metadata']['name'].removesuffix('-151-check'), 'token-labs/slot': 'release-151'}
        api['spec']['selector']['matchLabels'] = labels
        api['spec']['template']['metadata']['labels'] = deepcopy(labels)
        api_pod = api['spec']['template']['spec']
        api_pod['serviceAccountName'] = graph['metadata']['name'] + '-k8s-service-discovery'
        api_container = api_pod['containers'][0]
        api_container['image'] = NIGHTLY
        for env in api_container['env']:
            if 'value' in env:
                env['value'] = env['value'].replace(old_graph_name, graph['metadata']['name'])
        api_container['args'] = [arg.replace(old_graph_name, graph['metadata']['name']) for arg in api_container['args']]
        write(f'{short}-api-frontend.yaml', [api])
        stable = yaml.safe_load((HERE / 'inputs' / f'{short}-stable-service.yaml').read_text())
        if short == 'qwen':
            stable['metadata'].setdefault('labels', {})['token-labs/model'] = 'true'
        stable['spec']['selector']['token-labs/slot'] = 'blue' if short == 'qwen' else 'release-151'
        write(f'{short}-stable-service.yaml', [stable])


    public = yaml.safe_load((HERE / 'inputs/public-route.yaml').read_text())
    native = yaml.safe_load((HERE / 'inputs/native-route.yaml').read_text())
    for short, directory in MODELS.items():
        if not EPP_ROUTING_ENABLED[short]:
            continue
        graph = yaml.safe_load((HERE / f'{short}-graph.yaml').read_text())
        model = next(e['value'] for e in next(c for c in graph['spec']['components'] if c['type'] == 'epp')['podTemplate']['spec']['containers'][0]['env'] if e['name'] == 'DYN_MODEL_NAME')
        pool = graph['metadata']['name'] + '-pool'
        headers = [{'type': 'Exact', 'name': 'x-ai-eg-model', 'value': model}]
        public['spec']['rules'].insert(0, {'matches': [{'headers': deepcopy(headers) + [{'type': 'Exact', 'name': 'x-ai-eg-original-path', 'value': path}]} for path in ('/v1/chat/completions', '/v1/completions')],
            'timeouts': {'request': '3600s'}, 'backendRefs': [{'group': 'inference.networking.k8s.io', 'kind': 'InferencePool', 'name': pool}]})
    route_order = json.loads((HERE / 'route-order.json').read_text())
    public['spec']['rules'].sort(key=lambda rule: route_order.index(rule['backendRefs'][0]['name']))
    write('public-routes.yaml', [public, native])
    write('rollback-routes.yaml', [yaml.safe_load((HERE / 'inputs/public-route.yaml').read_text()), yaml.safe_load((HERE / 'inputs/native-route.yaml').read_text())])
    write('frontend-checks.yaml', candidates)
    write('platform-values.yaml', [{
        'kai-scheduler': {'scheduler': {'args': {'default-staleness-grace-period': '-1s'}}},
        'global': {'nats': {'install': True}, 'grove': {'install': True}, 'kai-scheduler': {'install': True}},
        'dynamo-operator': {'controllerManager': {'manager': {'image': {'repository': IMAGES['operator'].split(':1.5.1@')[0], 'tag': IMAGES['operator'].split(':', 1)[1]}}},
            'dynamo': {'metrics': {'prometheusEndpoint': 'http://prometheus-kube-prometheus-prometheus.monitoring.svc.cluster.local:9090'}}},
    }])
    (HERE / 'images.json').write_text(json.dumps({'version': '1.5.1', 'source_commit': '2093662a4d4e5fd318732935213dde08dc7be818', 'images': IMAGES, 'api_frontend_overlay': NIGHTLY}, indent=2) + '\n')


if __name__ == '__main__':
    main()
